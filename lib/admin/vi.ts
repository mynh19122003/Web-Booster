export function adminText(value: string): string {
  if (labels[value]) return labels[value];
  if (labels[value.toUpperCase()]) return labels[value.toUpperCase()];
  const patterns: [RegExp, string][] = [
    [/^Invited (.+) to the team$/, "Đã mời $1 vào đội ngũ"],
    [/^Approved (.+)’s application$/, "Đã duyệt hồ sơ của $1"],
    [/^(.+) joined the staff team$/, "$1 đã gia nhập đội ngũ quản trị"],
    [/^(.+) accepted an invitation$/, "$1 đã chấp nhận lời mời"],
    [/^Resent invitation to (.+)$/, "Đã gửi lại lời mời cho $1"],
    [
      /^Approved (.+) and sent credentials \(demo\)$/,
      "Đã duyệt $1 và gửi thông tin đăng nhập (dùng thử)",
    ],
    [/^Reviewed and declined (.+)$/, "Đã xét duyệt và từ chối $1"],
    [/^Revoked (.+)’s session$/, "Đã thu hồi phiên đăng nhập của $1"],
    [/^Assigned to (.+)$/, "Đã phân công cho $1"],
    [/^(.+) accepted$/, "$1 đã nhận việc"],
    [/^(.+) is ready to start$/, "$1 đã sẵn sàng bắt đầu"],
    [
      /^(.+) · Waiting for employee response$/,
      "$1 · Đang chờ nhân sự phản hồi",
    ],
    [/^(\d+)% of the journey complete\.$/, "Đã hoàn thành $1% tiến độ."],
    [/^(\d+)% complete · (\d+) LP\. (.*)$/, "Hoàn thành $1% · $2 LP. $3"],
    [/^(#ASC-\d+) was submitted$/, "$1 vừa được gửi"],
    [/^(.+) asked for an update$/, "$1 yêu cầu cập nhật"],
    [/^(.+) accepted (#ASC-\d+)$/, "$1 đã nhận $2"],
    [/^(.+) declined (#ASC-\d+)$/, "$1 đã từ chối $2"],
    [/^(#ASC-\d+) is complete$/, "$1 đã hoàn thành"],
  ];
  for (const [pattern, translation] of patterns) {
    if (pattern.test(value)) return value.replace(pattern, translation);
  }
  const orderDetail = value.match(/^(#ASC-\d+) · (.+)$/);
  if (orderDetail) return `${orderDetail[1]} · ${adminText(orderDetail[2])}`;
  return value;
}

const errorLabels: Record<number, string> = {
  401: "Phiên đăng nhập đã hết hạn. Vui lòng đăng nhập lại.",
  403: "Bạn không có quyền thực hiện thao tác này.",
  404: "Không tìm thấy dữ liệu.",
  409: "Dữ liệu đã thay đổi. Vui lòng tải lại trang.",
  422: "Vui lòng kiểm tra lại thông tin.",
  429: "Bạn thao tác quá nhanh. Vui lòng thử lại sau.",
  500: "Đã xảy ra lỗi hệ thống. Vui lòng thử lại.",
};
export function adminError(error: unknown): string {
  if (typeof error === "object" && error !== null) {
    const status =
      "status" in error
        ? Number(error.status)
        : "statusCode" in error
          ? Number(error.statusCode)
          : undefined;
    if (status && errorLabels[status]) return errorLabels[status];
  }
  const message =
    error instanceof Error
      ? error.message
      : typeof error === "string"
        ? error
        : "";
  const translated = adminText(message);
  if (translated !== message || /[\u00C0-\u024F\u1E00-\u1EFF]/.test(message))
    return translated;
  return errorLabels[500];
}
